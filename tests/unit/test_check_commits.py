from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[2] / "scripts" / "check_commits.py"
_spec = importlib.util.spec_from_file_location("check_commits", SCRIPT)
assert _spec and _spec.loader
check_commits = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(check_commits)
check_message = check_commits.check_message


@pytest.mark.parametrize(
    "message",
    [
        "feat: add state machine",
        "fix(store)!: fsync the directory after os.replace",
        "docs(adr): record spike S4 result\n\nBody explaining why.\n",
        "chore: bootstrap repository skeleton\n\n# Please enter the commit message\n",
        "docs: regenerate cli.md generated by gen_docs.py",
        "feat(hooks): read agent_type from Claude Code SubagentStop input",
        "Merge branch 'docs/adr-spikes'",
        'Revert "feat: add state machine"',
        "fixup! feat: add state machine",
        "test: cover human co-author\n\nCo-authored-by: Jane Doe <jane@example.com>",
    ],
)
def test_accepts(message: str) -> None:
    assert check_message(message) == []


@pytest.mark.parametrize(
    ("message", "needle"),
    [
        ("add state machine", "Conventional Commit"),
        ("Feat: add state machine", "Conventional Commit"),
        ("feat:missing space", "Conventional Commit"),
        ("feature: add x", "Conventional Commit"),
        ("feat: add x\nno blank line", "second line must be blank"),
        ("feat: " + "x" * 100, "limit"),
        ("", "empty"),
        ("feat: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>", "AI co-author"),
        ("feat: x\n\nco-authored-by: GitHub Copilot <copilot@github.com>", "AI co-author"),
        ("feat: x\n\n\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)", "AI attribution"),
        ("feat: x\n\nGenerated by ChatGPT", "AI attribution"),
        ("feat: x\n\nAssisted-by: Gemini", "AI assistance trailer"),
        ("feat: x\n\nThis is AI-generated.", "AI-generated"),
    ],
)
def test_rejects(message: str, needle: str) -> None:
    problems = check_message(message)
    assert problems, message
    assert any(needle in problem for problem in problems), problems


def test_scissors_section_is_ignored() -> None:
    message = (
        "feat: add x\n\n"
        "# ------------------------ >8 ------------------------\n"
        "diff --git a/x b/x\n+Co-Authored-By: Claude <noreply@anthropic.com>\n"
    )
    assert check_message(message) == []


def test_autosquash_rejected_in_range_mode() -> None:
    assert check_message("fixup! feat: add x", allow_autosquash=False)


def test_cli_msg_file(tmp_path: Path) -> None:
    good = tmp_path / "good"
    good.write_text("ci: add commit check\n", encoding="utf-8")
    bad = tmp_path / "bad"
    bad.write_text("wip\n", encoding="utf-8")
    run = [sys.executable, str(SCRIPT), "--msg-file"]
    assert subprocess.run([*run, str(good)], capture_output=True).returncode == 0
    result = subprocess.run([*run, str(bad)], capture_output=True, text=True)
    assert result.returncode == 1
    assert "Conventional Commit" in result.stderr
