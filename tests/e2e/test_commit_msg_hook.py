def test_real_merge_passes(repo: Path) -> None:
    git(repo, "switch", "-q", "-c", "side")
    assert commit(repo, *m("feat: on a side branch")).returncode == 0
    git(repo, "switch", "-q", "main")
    assert git(repo, "merge", "-q", "--no-ff", "--no-edit", "side", check=False).returncode == 0


def test_identity_is_enforced(repo: Path) -> None:
    result = commit(repo, "--author", "Someone Else <else@example.com>", *m("feat: x"))
    assert result.returncode != 0
    assert "author is 'Someone Else <else@example.com>'" in result.stderr


def test_hook_does_not_depend_on_checked_out_tree(tmp_path: Path) -> None:
    repo = make_repo(tmp_path / "repo")
    assert not (repo / "scripts").exists()
    assert commit(repo, *m("chore: works without the checker in the tree")).returncode == 0
    assert commit(repo, *m("not conventional")).returncode != 0


def test_range_checks_stored_messages_verbatim(tmp_path: Path) -> None:
    repo = make_repo(tmp_path / "repo")
    assert commit(repo, *m("feat: good")).returncode == 0
    assert checker(repo, "--range", "HEAD^!", "--expect-identity", IDENTITY).returncode == 0
    wrong_identity = checker(repo, "--range", "HEAD^!", "--expect-identity", "Other <o@example.com>")
    assert wrong_identity.returncode == 1
    assert "expected 'Other <o@example.com>'" in wrong_identity.stderr

    bypassed = {
        "comment-trailer": m("feat: x", "# Co-Authored-By: Claude <noreply@anthropic.com>"),
        "single-parent-merge-header": m("Merge branch because I say so"),
        "autosquash": m("fixup! feat: good"),
    }
    for name, args in bypassed.items():
        assert commit(repo, "--no-verify", *args).returncode == 0, name
        result = checker(repo, "--range", "HEAD^!")
        assert result.returncode == 1, name
