CHECKER = Path(__file__).resolve().parents[2] / "scripts" / "check_commits.py"
IDENTITY = "Test User <test@example.com>"


def git(repo: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True, check=check)  # noqa: S607


def checker(repo: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run([sys.executable, str(CHECKER), *args], cwd=repo, capture_output=True, text=True)


def make_repo(path: Path, *install_args: str) -> Path:
    path.mkdir()
    git(path, "init", "-q", "-b", "main")
    git(path, "config", "user.name", "Test User")
    git(path, "config", "user.email", "test@example.com")
    git(path, "config", "commit.gpgsign", "false")
    git(path, "commit", "-q", "--allow-empty", "--no-verify", "-m", "chore: root")
    assert checker(path, "--install-hook", *install_args).returncode == 0
    return path


@pytest.fixture(scope="module")
def repo(tmp_path_factory: pytest.TempPathFactory) -> Iterator[Path]:
    yield make_repo(tmp_path_factory.mktemp("hook") / "repo", "--expect-identity", IDENTITY)


def commit(repo: Path, *args: str, message_file: str | None = None) -> subprocess.CompletedProcess[str]:
    extra: list[str] = []
    if message_file is not None:
        path = repo.parent / "MSG"
        path.write_text(message_file, encoding="utf-8")
        extra = ["-F", str(path)]
    return git(repo, "commit", "--allow-empty", *extra, *args, check=False)


def m(*paragraphs: str) -> list[str]:
    return [arg for p in paragraphs for arg in ("-m", p)]


